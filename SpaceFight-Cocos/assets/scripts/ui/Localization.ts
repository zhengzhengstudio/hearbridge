function localize(base: CombatMessages, overrides: Partial<CombatMessages>): CombatMessages {
  return { ...base, ...overrides };
}

export const COMBAT_HUD_MESSAGES: Readonly<Record<CombatLocale, CombatMessages>> = {
  'zh-CN': zhCN, 'zh-TW': zhTW, en, ja, ko, es, 'pt-BR': ptBR, fr,
};

export function resolveCombatLocale(languages: readonly string[] = []): CombatLocale {
  for (const language of languages) {
    const normalized = language.trim().replace(/_/g, '-').toLowerCase();
    if (!normalized) continue;
    if (normalized.startsWith('zh-hant') || normalized.startsWith('zh-tw') || normalized.startsWith('zh-hk') || normalized.startsWith('zh-mo')) return 'zh-TW';
    if (normalized.startsWith('zh')) return 'zh-CN';
    if (normalized.startsWith('pt')) return 'pt-BR';
    const base = normalized.split('-')[0];
    if (base === 'en' || base === 'ja' || base === 'ko' || base === 'es' || base === 'fr') return base;
  }
  return 'zh-CN';
}

export function detectCombatLocale(source?: { readonly languages?: readonly string[]; readonly language?: string }): CombatLocale {
  const browser = source ?? (typeof navigator !== 'undefined' ? navigator : undefined);
  const languages = browser?.languages?.length
    ? browser.languages
    : browser?.language ? [browser.language] : [];
  return resolveCombatLocale(languages);
}

export function combatText(locale: CombatLocale, key: CombatMessageKey, params: CombatTextParams = {}): string {
  // 非法 locale / 缺失 key 在运行时不应抛 TypeError（存档或旧客户端可能传入脏值）。
  const fallback = COMBAT_HUD_MESSAGES['zh-CN'];
  const catalog: CombatMessages = COMBAT_HUD_MESSAGES[locale] || fallback;
  const template: string = catalog[key] || fallback[key] || String(key);
  return template.replace(/\{(\w+)\}/g, (token, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : token
  ));
}
