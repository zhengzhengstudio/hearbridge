    setLanguage: function(lang) {
        this.currentLang = lang;
        this.updateUI();
    },
    
    get: function(key) {
        var lang = this.currentLang;
        if (this.translations[lang] && this.translations[lang][key]) {
            return this.translations[lang][key];
        }
        return key;
    },
    
    updateUI: function() {
        document.getElementById('btn-play').textContent = this.get('start_game');
        document.getElementById('btn-multiplayer').textContent = this.get('multiplayer');
        document.getElementById('btn-settings').textContent = this.get('settings');
        document.getElementById('btn-mods').textContent = this.get('mods');
        document.getElementById('btn-quit').textContent = this.get('quit');
        document.querySelector('.loading-text').textContent = this.get('loading');
    }
