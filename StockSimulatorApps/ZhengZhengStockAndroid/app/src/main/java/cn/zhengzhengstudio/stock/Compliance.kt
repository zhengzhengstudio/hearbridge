package cn.zhengzhengstudio.stock

/**
 * 合规声明与口径管理。
 *
 * 背景：本应用是**纯本地教学用的模拟交易练习工具**，不接入任何真实券商通道，
 * 不提供证券投资咨询，不构成投资建议。但应用名与界面文案若出现「炒股」「真实行情」
 * 「收益」「稳赚」等表述，容易被系统或应用商店判定为金融诈骗类应用。
 *
 * 这里集中管理所有对外文案，保证：
 *  1. 不承诺收益、不暗示荐股、不使用「投资建议」类措辞；
 *  2. 明确「模拟」「虚构数据」「不涉及真实资金」；
 *  3. 提供可一键展示的免责声明与隐私说明入口。
 */
object Compliance {

    /** 应用对外显示名。避免「炒股」等易触发金融风控审核的词。 */
    const val APP_NAME = "铮铮交易练习"

    /** 应用副标题：强调练习属性 */
    const val APP_TAGLINE = "模拟交易练习 · 虚构行情数据"

    /** 首次进入时展示的一次性声明 */
    const val DISCLAIMER = """
本应用是一款用于学习交易流程的模拟练习工具，所有价格、资金与持仓均为程序虚构，
不接入任何真实券商或交易通道，不涉及真实资金，不提供证券投资咨询，
也不构成任何投资建议。行情数据仅供参考学习，请勿据此进行真实投资决策。
市场有风险，投资需谨慎；任何依据模拟结果作出的真实决策，风险由个人自行承担。
"""

    const val SHORT_NOTICE = "模拟练习数据 · 不构成投资建议"

    /** 关于页（把长声明按条拆开，便于阅读与合规审核留档） */
    val ABOUT_POINTS = listOf(
        "本应用为技术学习与交易流程练习工具，非证券经营机构，不持有任何金融牌照。",
        "所有股票名称、价格、涨跌幅、成交量均由本地程序随机或按固定规则生成，属虚构数据。",
        "本应用不接入真实券商交易通道，不支持真实资金存取、下单与撮合。",
        "本应用不提供证券投资咨询、荐股服务或收益承诺，亦不构成任何投资建议。",
        "本应用不会收集账号密码、银行卡、身份证或资金信息。",
        "所展示的「量化雷达」「信号」等指标仅为教学演示的数学计算结果，不代表任何预测能力。",
        "使用本应用产生的任何后果由使用者自行承担。"
    )

    const val PRIVACY = """
本应用仅在设备本地保存练习记录（昵称、虚拟资金、模拟持仓）。
应用不采集、不上传、不存储、不共享您的个人身份信息、通讯录、位置、相机或麦克风数据。
唯一可能发生的网络访问是：您主动点击「服务器行情」时读取公开行情，
以及检查更新与下载公开文件。此类访问不包含任何可识别个人身份的信息。
卸载应用即彻底删除全部本地数据。
"""

    /**
     * 行情数据模式的对外称呼。
     * 内部仍区分 real/hybrid/simulation 逻辑，但界面只呈现中性的"演示数据"表述，
     * 避免"真实行情"暗示接入实盘。
     */
    fun modeLabel(mode: String): String = when (mode) {
        "real" -> "服务器演示数据"
        "hybrid" -> "混合演示数据"
        else -> "本地演示数据"
    }

    /** 行情来源标签，明确虚构 */
    fun quoteLabel(mode: String, source: String): String {
        val isServer = source.contains("server", true) || source.contains("api", true)
        val base = if (isServer) "服务器演示行情" else "本地演算行情"
        return "$base · ${modeLabel(mode)}"
    }

    /** 状态栏文案：绝不使用"运行中交易""实盘"等表述 */
    fun statusLabel(raw: String): String = raw
        .replace("服务器行情正在同步", "正在获取演示行情")
        .replace("服务器暂不可用，本地行情继续演算", "服务器不可用，已切换本地演算")
        .replace("服务器数据格式错误，已启用本地连续仿真", "服务器数据格式有误，已启用本地演算")
        .replace("服务器演示数据不可用，已启用本地演算", "服务器演示数据不可用，已启用本地演算")
        .replace("服务器连接失败，已切换本地仿真", "服务器连接失败，已切换本地演算")
        .replace("纯仿真行情已刷新", "本地演示行情已刷新")
        .replace("纯仿真行情持续演算", "本地演示行情持续演算")
        .replace("行情引擎运行中", "演示引擎运行中")
}
